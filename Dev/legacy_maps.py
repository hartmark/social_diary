#!/usr/bin/env python3
"""Embed original-client map metadata, without redistributing its textures.

Usage: python3 Dev/legacy_maps.py WorldMapArea.dbc WorldMapOverlay.dbc
       [--output Core/Legacy.lua]

Input schemas are original Wrath build 12340. Texture folders, world bounds
and overlay geometry come from the client's own tables. Runtime map IDs are
resolved independently by its native map API.
"""
import argparse
import json
from pathlib import Path
import struct


def dbc(path, fields):
    data = Path(path).read_bytes()
    magic, count, columns, size, strings = struct.unpack_from('<4s4I', data)
    if magic != b'WDBC' or columns != fields or size != fields * 4:
        raise ValueError(f'{path}: unexpected build/schema')
    start = 20 + count * size
    def string(offset):
        if offset >= strings:
            raise ValueError('invalid string offset')
        p = start + offset
        return data[p:data.index(b'\0', p)].decode('utf-8')
    rows = [struct.unpack_from('<' + 'I' * fields, data, 20 + i * size) for i in range(count)]
    return data, rows, string


def generate(area_path, overlay_path):
    data, areas, text = dbc(area_path, 11)
    _, overlays, overlay_text = dbc(overlay_path, 17)
    by_id = {}
    for row in overlays:
        name = overlay_text(row[8])
        if name and row[9] and row[10]:
            by_id.setdefault(row[1], []).append((name, *row[9:13]))
    lines = ['-- BEGIN GENERATED LEGACY MAP CATALOG',
             '-- Generated by Dev/legacy_maps.py from original Wrath build 12340.',
             '-- Folder, map instance, area, world Y/X bounds, and overlay geometry.',
             'local mapCatalog = {']
    for i, row in enumerate(areas):
        name = text(row[3])
        if not name:
            continue
        bounds = struct.unpack_from('<4f', data, 20 + i * 44 + 16)
        if not all(abs(v) < 1e8 for v in bounds):
            raise ValueError('invalid map bounds')
        l, r, t, b = (format(v, '.10g') for v in bounds)
        lines.append(f'    [{json.dumps(name.lower())}] = {{ folder = {json.dumps(name)}, instance = {row[1]}, areaID = {row[2]},')
        lines.append(f'        left = {l}, right = {r}, top = {t}, bottom = {b}, overlays = {{')
        for overlay in by_id.get(row[0], []):
            n, w, h, x, y = overlay
            lines.append(f'            {{ {json.dumps(n)}, {w}, {h}, {x}, {y} }},')
        lines.append('        } },')
    lines.extend(['}', '-- END GENERATED LEGACY MAP CATALOG'])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('areas')
    parser.add_argument('overlays')
    parser.add_argument('--output', type=Path, default=Path('Core/Legacy.lua'))
    args = parser.parse_args()
    source = args.output.read_text()
    first = source.index('-- BEGIN GENERATED LEGACY MAP CATALOG')
    marker = '-- END GENERATED LEGACY MAP CATALOG'
    last = source.index(marker, first) + len(marker)
    args.output.write_text(source[:first] + generate(args.areas, args.overlays) + source[last:])


if __name__ == '__main__':
    main()
