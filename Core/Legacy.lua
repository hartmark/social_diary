end
local function OverlayFiles(folder, name, width, height)
    local files = {}
    local prefix = 'Interface\\WorldMap\\' .. folder .. '\\' .. name
    for i = 1, math.ceil(width / 256) * math.ceil(height / 256) do files[i] = prefix .. i end
    return files
end
function Map.GetMapArtLayers(id)
    local info = Info(id)
    if not info then return nil end
    local data = info.data
    if not data.layer then
        local overlays = {}
        for _, area in ipairs(data.overlays) do
            local name, w, h, x, y = unpack(area)
            overlays[#overlays + 1] = { w, h, x, y, OverlayFiles(data.folder, name, w, h) }
        end
        data.layer = { layerWidth = 1002, layerHeight = 668, tileWidth = 256, tileHeight = 256,
            legacyMap = true, legacyOverlays = overlays }
    end
    return { data.layer }
end
function Map.GetMapArtLayerTextures(id, layer)
    if layer ~= 1 then return nil end
    local info = Info(id)
    if not info then return nil end
    local folder, textures = info.data.folder, {}
    local prefix = 'Interface\\WorldMap\\' .. folder .. '\\' .. folder
    for i = 1, 12 do textures[i] = prefix .. i end
    return textures
end
function Map.GetMapWorldSize(id)
    local info = Info(id)
    if not info then return nil end
    local d = info.data
    return math.abs(d.right - d.left), math.abs(d.bottom - d.top)
end
function Map.GetWorldPosFromMapPos(id, pos)
    local info = Info(id)
    if not info then return nil end
    local x, y = pos:GetXY()
    local d = info.data
    return d.instance, Vector(d.left + (d.right - d.left) * x, d.top + (d.bottom - d.top) * y)
end
function Map.GetMapPosFromWorldPos(instance, pos, id)
    local info = Info(id)
    if not info or info.data.instance ~= instance then return nil end
    local d, x, y = info.data, pos:GetXY()
    if d.left == d.right or d.top == d.bottom then return nil end
    return id, Vector((x - d.left) / (d.right - d.left), (y - d.top) / (d.bottom - d.top))
end
