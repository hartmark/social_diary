local maps, mapBusy = {}, false
local function Vector(x, y)
    return { x = x, y = y, GetXY = function() return x, y end,
        GetX = function() return x end, GetY = function() return y end }
end
API('CreateVector2D', Vector)
local function NativeMap(id, current, fn)
    if mapBusy then return nil end
    -- In build 12340 the getter returns DBC ID + 1, while SetMapByID
    -- accepts the DBC ID. Blizzard subtracts one in its own WorldMapFrame
    -- window-size restoration code. Keep stored IDs in the getter namespace.
    local oldID, oldFloor = GetCurrentMapAreaID(), GetCurrentMapDungeonLevel()
    if WorldMapFrame and WorldMapFrame:IsShown() and (current or oldID ~= id) then return nil end
    local oldContinent = GetCurrentMapContinent and GetCurrentMapContinent()
    local oldZone = GetCurrentMapZone and GetCurrentMapZone()
    mapBusy = true
    local changed = current or oldID ~= id
    local result = { pcall(function()
        if current then SetMapToCurrentZone()
        elseif changed then SetMapByID(id - 1) end
        if id and GetCurrentMapAreaID() ~= id then return nil end
        return fn()
    end) }
    -- Restore even when the read failed. Do not change an open world map.
    local restored, restoreError = pcall(function()
        if changed then
            if oldID and oldID > 0 then SetMapByID(oldID - 1)
            elseif SetMapZoom and oldContinent then SetMapZoom(oldContinent, oldZone or 0) end
            if oldFloor and oldFloor > 0 then SetDungeonMapLevel(oldFloor) end
        end
    end)
    mapBusy = false
    if not result[1] then error(result[2], 0) end
    if not restored then error(restoreError, 0) end
    return unpack(result, 2)
end
local function BindMap()
    local id, folder = GetCurrentMapAreaID(), GetMapInfo()
    if not id or id <= 0 or type(folder) ~= 'string' then return nil end
    local data = mapCatalog[folder:lower()]
    if not data then return nil end
    local name
    if GetCurrentMapContinent and GetCurrentMapZone and GetMapZones then
        local continent, zone = GetCurrentMapContinent(), GetCurrentMapZone()
        if continent and continent > 0 and zone and zone > 0 then
            name = select(zone, GetMapZones(continent))
        end
    end
    local info = maps[id]
    if not info or info.data ~= data then
        info = { mapID = id, name = name or data.folder,
            mapType = data.areaID > 0 and 3 or 2, parentMapID = 0, data = data }
        maps[id] = info
    elseif name then info.name = name end
    return info
end
local function Info(id)
    if maps[id] then return maps[id] end
    if type(id) ~= 'number' or id <= 0 then return nil end
    return NativeMap(id, false, BindMap)
end
-- Zone, normalized position and physical world coordinates must describe
-- the same instant. Reuse one native-map read during this game frame.
local snapshot, snapshotAt
local function Snapshot()
    if WorldMapFrame and WorldMapFrame:IsShown() then return nil end
    local now = GetTime()
    if snapshotAt == now then return snapshot end
    snapshotAt = now
    snapshot = NativeMap(nil, true, function()
        local info = BindMap()
        if not info or info.mapType ~= 3 then return nil end
        local x, y = GetPlayerMapPosition('player')
        if type(x) ~= 'number' or type(y) ~= 'number' or (x == 0 and y == 0) then return nil end
        return { mapID = info.mapID, x = x, y = y, data = info.data }
    end)
    return snapshot
end
